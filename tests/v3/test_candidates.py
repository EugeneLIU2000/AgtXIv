@pytest.mark.parametrize('change', ['omitted_segment', 'gap', 'file_count', 'classification', 'approval', 'missing_artifact', 'wrong_bytes', 'record_ref'])
def test_tampered_packages_rollback(tmp_path, bundle, inspection, change):
    package = build_candidate_package(inspection)
    body = package.report()
    artifacts = list(package.artifacts)
    if change == 'omitted_segment': body['segments'].pop()
    if change == 'gap': body['segments'][0]['start_byte'] = 1
    if change == 'file_count': body['file_count'] -= 1
    if change == 'classification': body['segments'][0]['classification'] = 'PUBLISHED_CLAIM'
    if change == 'approval': body['scientific_assessment'] = 'APPROVED'
    if change == 'record_ref':
        body['record_refs'] = [{'record_type': 'agtxiv.v3.claim/0.0.0', 'record_id': 'claim:absent', 'revision': 1, 'content_hash': 'sha256:' + '0' * 64}]
    if change in {'missing_artifact', 'wrong_bytes'}:
        identifier = body['files'][0]['artifact']['artifact_id']
        artifacts = [a for a in artifacts if a.artifact_id != identifier]
        if change == 'wrong_bytes': artifacts.append(SuppliedArtifact(identifier, body['files'][0]['artifact']['media_type'], b'wrong'))
    artifact = _artifact(canonical(body), 'application/json')
    artifacts = [a for a in artifacts if a.artifact_id != package.artifact.artifact_id] + [artifact]
    bad = CandidatePackage(artifact, tuple(artifacts))
    with LocalStore(tmp_path / 'db', bundle) as store:
        with pytest.raises((ContractError, SourceError)):
            persist_candidate_package(store, bad)
        assert store._db.execute('SELECT count(*) FROM artifacts').fetchone() == (0,)


def test_real_pinned_robustness_whole_directory(tmp_path, bundle):
    root = ROOT / 'Reference/Application of a resource theory for magic states to fault-tolerant quantum computing'
    main = 'Robustness_main_appendix.tex'
    inspection = inspect_source_directory(root, main)
    original = inspection.sources[main]
    assert len(original) == 56170
    assert hashlib.sha256(original).hexdigest() == '48adf581a5f8353bb1125c75b8e0a075ff7ba79917f2a12d9f7e0f4ad1a8312d'
    with tarfile.open(fileobj=io.BytesIO(inspection.sources['source.tar'])) as archive:
        members = [m for m in archive.getmembers() if m.isfile()]
        assert len(members) == 5
        names = set()
        for member in members:
            name = member.name.removeprefix('./')
            names.add(name)
            assert archive.extractfile(member).read() == inspection.sources[name]
    originals = names | {'source.tar'}
    assert len(originals) == 6
    assert all(p.startswith('build/') for p in inspection.sources.keys() - originals)
    from agtxiv_v3.candidates import build_local_proposed_context, build_interpretation_records
    from agtxiv_v3.contracts import RecordSet, exact_ref, kind
    from agtxiv_v3.dependencies import inspect_dependencies
    context = build_local_proposed_context(inspection, bundle=bundle,
        corpus_bytes=(ROOT / 'schema v0.0/evaluation-corpus.json').read_bytes())
    records = (context['source_snapshot'], context['paper_structure'], *build_interpretation_records(
        inspection, robustness_proposals(inspection), source_snapshot=context['source_snapshot'],
        bundle=bundle, producer=context['producer'], policy_ref=context['policy_ref'], created_at=context['created_at']))
    kwargs = dict(proposals=robustness_proposals(inspection), open_questions=ROBUSTNESS_QUESTIONS,
                  records=records, supporting_artifacts=context['artifacts'])
    package = build_candidate_package(inspection, **kwargs)
    assert all(not bundle.validate_record(r) for r in (*records, *context['context_records']))
    policy = context['context_records'][0]
    assert policy['payload']['charter_state'] == 'PROPOSED'
    assert policy['payload']['allowed_principal_ids'] == []
    assert policy['payload']['ratification_commit'] is None
    assert context['source_snapshot']['payload']['missing_material']
    assert all(r['producer']['identity_assurance'] == 'DECLARED' for r in records)
    nodes = {p['id']: r for p, r in zip(robustness_proposals(inspection), [r for r in records if kind(r) == 'argument-node'])}
    record_set = RecordSet(bundle, (*context['context_records'], *records), package.artifacts)
    assert record_set.validate(require_artifacts=True).valid
    for trigger in ('definition', 'channel'):
        impact = inspect_dependencies(record_set, [exact_ref(nodes[trigger])])
        assert exact_ref(nodes['R3']) in [a['target_ref'] for a in impact.payload['affected']]
        assert exact_ref(nodes['postselection']) not in [a['target_ref'] for a in impact.payload['affected']]
    obligations = package.report()['proposed_obligations']
    assert obligations and all(o['state'] == 'OPEN' and o['disposition'] == 'DEFERRED' and not o['performed'] for o in obligations)
    assert all(o['frozen_scope_ref'] is None and o['evidence_refs'] == [] for o in obligations)
    assert all(o['target_refs'] or o['source_artifact_refs'] for o in obligations)
    inventory = package.report()['candidate_inventory']
    assert inventory['semantic_claim_denominator'] is None
    assert inventory['main_line_count'] == 548
    assert sum(inventory['main_bucket_counts'].values()) == 548
    assert all(inventory['main_bucket_counts'].values())
    assert package.report()['file_count'] == len(inspection.sources)
    assert len(package.report()['segments']) >= 548
    assert package == build_candidate_package(inspection, **kwargs)
    with LocalStore(tmp_path / 'real.sqlite', bundle) as store:
        assert persist_candidate_package(store, package, context_records=context['context_records']).valid
    with LocalStore(tmp_path / 'real.sqlite', bundle, readonly=True) as store:
        result = query_candidate_package(store, package.reference())
        proposals = {p['id']: p for p in result['package']['proposals']}
        anchor = proposals['R3']['anchors'][0]
        assert original[anchor['start_byte']:anchor['end_byte']].startswith(b'    \\item[R3]')
        assert proposals['postselection']['dependencies'] == []
        assert 'R3' not in proposals['postselection']['dependencies']
        assert all(p['verification'] == 'UNVERIFIED' for p in proposals.values())
    assert (root / main).read_bytes() == original


