def test_existing_contract_projection_requires_real_caller_context(tmp_path, bundle, inspection):
    from agtxiv_v3.candidates import build_interpretation_records
    from agtxiv_v3.contracts import exact_ref
    from agtxiv_v3.intake import build_source_candidates
    from test_contracts import FixtureGraph
    from test_intake import caller_metadata
