    metadata = caller_metadata(bundle)
    metadata['policy_ref'] = exact_ref(graph.policy)
    source = build_source_candidates(inspection, **metadata)
    proposals = [proposal(inspection)]
    second = copy.deepcopy(proposals[0])
    second.update(id='dependent', dependencies=['candidate'])
    proposals.append(second)
    kwargs = dict(source_snapshot=source.source_snapshot, bundle=bundle,
                  producer=metadata['producer'], policy_ref=metadata['policy_ref'], created_at=metadata['created_at'])
